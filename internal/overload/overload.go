/*
 * Строки перегрузки профиля: «когда инспектор перегружен -> что сделать».
 *
 * Порог -- заполнение очереди инспектора в процентах в миг, когда запрос в
 * неё встал. Ниже порога строка молчит. От порога до края инспектор
 * проверяет запрос как обычно, запрос получает настоящий вердикт, а действие
 * строки уезжает рядом с ним: смысл порога в том, чтобы разгрузиться до того,
 * как очередь переполнится. На краю -- очередь полна, запрос сброшен --
 * вердикта нет, и действие уезжает рядом с verdict: error; что делать с самим
 * запросом, решает waf_exception ... overload маршрута.
 *
 * Действие у строки то же, что у остальных строк профиля: просьба соседу,
 * запись маршрута либо запись в набор, и выбирает его администратор. На
 * ответе error модуль исполняет только свои глаголы, просьбы соседям не
 * доезжают; запись в набор делает сам инспектор, и она уезжает всегда.
 *
 * Строки перегрузки -- только на фазе запроса: очередь одна на все фазы, а
 * решение «что делать с клиентом, пока мы тонем» принимается один раз на
 * запрос.
 *
 * Файл один и тот же у всех инспекторов с такими строками: смысл порога не
 * должен разъехаться между ними.
 */

package overload

import "fmt"

const (
	// On -- слово условия строки.
	On = "overload"

	// AtMin -- ниже строка срабатывала бы на любой рабочей очереди, то есть
	// всегда, а «всегда» -- это не триггер.
	AtMin = 25

	// AtMax -- край: очередь полна, запрос сброшен. Это и умолчание: строка
	// без порога ведёт себя как строка, написанная до появления порога.
	AtMax = 100
)

// At -- порог строки с умолчанием.
func At(at *int) int {
	if at == nil {
		return AtMax
	}

	return *at
}

// Check -- порог в пределах шкалы. Не назван -- законно: это край.
func Check(at *int) error {
	if at == nil {
		return nil
	}

	if *at < AtMin || *at > AtMax {
		return fmt.Errorf("at %d is out of %d..%d percent of the queue", *at, AtMin, AtMax)
	}

	return nil
}

/*
 * Fires -- срабатывает ли строка с порогом at. fill -- заполнение очереди при
 * постановке запроса, shed -- запрос сброшен по полной очереди.
 *
 * На сбросе срабатывает любая строка: полная очередь выше любого порога. На
 * проверенном запросе -- только строка ниже края: край значит «запрос
 * сброшен», и строка с ним молчит, даже если запрос дождался места в полной
 * очереди. Протухший бюджет перегрузкой не считается: дедлайн бывает и у
 * короткой волны, и действие за латентность контура было бы действием ни за
 * что.
 */
func Fires(at, fill int, shed bool) bool {
	if shed {
		return true
	}

	return at < AtMax && fill >= at
}
